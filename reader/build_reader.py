#!/usr/bin/env python3
"""
TRANSMISSION READER 98 — data builder
-------------------------------------
Reads the site's existing data (read-only) and writes reader/mailbox.js.
Touches nothing outside the reader/ folder.

    python3 reader/build_reader.py            # from the repo root

Inputs  (never modified): _data/notes_with_media_compact.json,
                          _data/magazine_articles.json, minimags.html
Output:                   reader/mailbox.js  ->  const MAILBOX = {...};
"""
import datetime as dt
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# Data folder: the repo's _data/ by default; set MM_DATA to build from another copy.
DATA = os.environ.get("MM_DATA") or os.path.join(ROOT, "_data")
OUT = os.path.join(HERE, "mailbox.js")
NOTE_PREFIX = ("https://substackcdn.com/image/fetch/$s_!G4Yk!,w_400,c_limit,f_webp,"
               "q_auto:good,fl_progressive:steep/"
               "https%3A%2F%2Fsubstack-post-media.s3.amazonaws.com%2Fpublic%2Fimages%2F")
COVER_PREFIX = NOTE_PREFIX.replace("w_400", "w_600")


def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def tail(url, prefix):
    if not url:
        return ""
    return url[len(prefix):] if url.startswith(prefix) else url


def monday(iso):
    d = dt.date.fromisoformat(iso)
    return (d - dt.timedelta(days=d.weekday())).isoformat()


def main():
    notes = load(os.path.join(DATA, "notes_with_media_compact.json"))
    articles = load(os.path.join(DATA, "magazine_articles.json"))
    with open(os.path.join(ROOT, "minimags.html"), encoding="utf-8") as f:
        issued = set(re.findall(r'href="((?:week|month)-[\d-]+)\.html"', f.read()))

    notes = sorted(notes, key=lambda n: (n["d"], n["id"]), reverse=True)
    # [id, date, likes, restacks, text, image tail, tags, video]
    rows = [[n["id"], n["d"], n.get("l", 0), n.get("r", 0), (n.get("b") or "").strip(),
             tail(n.get("t"), NOTE_PREFIX), ",".join(n.get("c") or []), 1 if n.get("m") else 0]
            for n in notes]

    weeks, months = {}, {}
    for n in notes:
        for key, bucket in ((monday(n["d"]), weeks), (n["d"][:7], months)):
            b = bucket.setdefault(key, {"n": 0, "l": 0, "best": []})
            b["n"] += 1
            b["l"] += n.get("l", 0)
            b["best"].append((n.get("l", 0), n["id"]))

    def issues(bucket, kind):
        out = []
        for k in sorted(bucket, reverse=True):
            if f"{kind}-{k}" not in issued:
                continue
            b = bucket[k]
            out.append({"k": k, "n": b["n"], "l": b["l"],
                        "top": [i for _, i in sorted(b["best"], reverse=True)[:3]]})
        return out

    arts = [{"d": a["date"], "t": a["title"].strip(), "s": (a.get("subtitle") or "").strip(),
             "u": a["url"], "nl": "Art" if "Art" in a.get("newsletter", "") else "TV",
             "c": tail(a.get("cover_url"), COVER_PREFIX), "p": (a.get("preview") or "")[:420],
             "l": a.get("likes"), "cm": a.get("comments"), "r": a.get("restacks"), "wd": a.get("words")}
            for a in sorted(articles, key=lambda a: a["date"], reverse=True)]

    data = {
        "built": dt.date.today().isoformat(),
        "notePrefix": NOTE_PREFIX,
        "coverPrefix": COVER_PREFIX,
        "notes": rows,
        "weekly": issues(weeks, "week"),
        "monthly": issues(months, "month"),
        "articles": arts,
    }
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* generated by reader/build_reader.py — do not edit by hand */\n")
        f.write(f"const MAILBOX = {payload};\n")
    print(f"mailbox.js: {len(rows):,} notes, {len(data['weekly'])} weekly + "
          f"{len(data['monthly'])} monthly issues, {len(arts)} articles, "
          f"{os.path.getsize(OUT)/1024:.0f} KB")


if __name__ == "__main__":
    main()
