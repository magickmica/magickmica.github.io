/* ============================================================
   MAGICK MICA · EXPLORE                     explore/explore.js
   ------------------------------------------------------------
   Shared by every page in explore/. Loads after:
     ../archive.js       (window.MMArchive: dates, url, random, announce)
     notes-data.js       (window.MM_NOTES, generated by build_explore.py)

   window.MMX gives each page:
     MMX.notes      every note as an object, oldest first
     MMX.byId       id -> note
     MMX.ready(fn)  run fn(notes) once data is in, or show the error state
     MMX.chrome(o)  header, Explore nav and footer for the page
     MMX.card(n,o)  a note card element
     MMX.viewer     an accessible note viewer (dialog) with prev/next
   ============================================================ */
(function (root) {
  'use strict';
  var A = root.MMArchive;
  var esc = A.util.escapeHtml;
  var SITE = '../';
  var NOTE_URL = 'https://substack.com/@magickmica/note/c-';

  /* the Explore pages, in menu order. `here` marks the current one */
  var PAGES = [
    { href: 'index.html',   name: 'Explore',            short: 'Explore' },
    { href: 'book.html',    name: 'The Transmission Book', short: 'Book' },
    { href: 'gallery.html', name: 'The Gallery Wing',   short: 'Gallery' },
    { href: 'tapes.html',   name: 'The Tape Library',   short: 'Tapes' },
    { href: 'sky.html',     name: 'The Sky Map',        short: 'Sky Map' },
    { href: 'themes.html',  name: 'Theme Rooms',        short: 'Themes' },
    { href: 'hall.html',    name: 'The Hall of Fame',   short: 'Hall of Fame' }
  ];

  /* ── data ─────────────────────────────────────────────────── */
  var notes = [], byId = {};
  function decode(raw) {
    var pre = raw.img || '';
    return raw.notes.map(function (r, i) {
      var t = r[3] || '';
      var img = t ? (/^https?:/.test(t) ? t : pre + t) : '';
      var n = { id: r[0], d: r[1], b: r[2] || '', img: img, m: r[4] || '',
                l: r[5] || 0, r: r[6] || 0, c: r[7] || [], i: i };
      /* the CDN file name carries the original size, e.g. _1024x1536.png */
      var wh = /_(\d{2,5})x(\d{2,5})\.\w+$/.exec(t);
      if (wh) { n.w = +wh[1]; n.h = +wh[2]; }
      n.url = NOTE_URL + n.id;
      n.thumb = img || (n.m ? 'https://image.mux.com/' + n.m + '/thumbnail.jpg?width=400' : '');
      n.kind = n.m ? 'video' : img ? 'image' : 'text';
      return n;
    });
  }
  /* a larger copy of a note image for the viewer: same CDN, wider */
  function big(n) {
    if (!n.img) return n.thumb;
    return n.img.replace(/,w_\d+,/, ',w_1200,');
  }
  function excerpt(s, max) {
    s = String(s || '').replace(/https?:\/\/\S+/g, '').replace(/\s+/g, ' ').trim();
    max = max || 140;
    if (s.length <= max) return s;
    return s.slice(0, max).replace(/\s+\S*$/, '') + '…';
  }
  function firstLine(s, max) {
    var line = String(s || '').split(/\n/).map(function (x) { return x.trim(); })
      .filter(function (x) { return x && !/^https?:/.test(x); })[0] || '';
    return excerpt(line, max || 60);
  }

  function ready(fn) {
    function go() {
      var main = document.getElementById('main');
      if (!root.MM_NOTES || !root.MM_NOTES.notes) {
        if (main) main.innerHTML =
          '<div class="ar-panel ar-state ar-state--error" role="alert">' +
          '<div class="ar-noise" aria-hidden="true"></div>' +
          '<p class="ar-state__title">THE SIGNAL DROPPED.</p>' +
          '<p class="ar-state__body">The notes archive did not load. Check your connection and try again.</p>' +
          '<button class="ar-btn" type="button" onclick="location.reload()">Retry</button></div>';
        return;
      }
      if (!notes.length) {
        notes = decode(root.MM_NOTES);
        notes.forEach(function (n) { byId[n.id] = n; });
        api.notes = notes; api.byId = byId;
      }
      document.documentElement.classList.add('mmx-ready');
      fn(notes);
    }
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', go);
    else go();
  }

  /* ── page chrome ──────────────────────────────────────────── */
  function chrome(o) {
    var here = o.here;
    var cur = PAGES.filter(function (p) { return p.href === here; })[0] || PAGES[0];
    var head = document.getElementById('mmx-head');
    if (head) {
      var crumbs = '<ol class="ar-crumbs"><li><a href="' + SITE + 'index.html">Home</a></li>' +
        '<li><a href="' + SITE + 'notes.html">Notes</a></li>' +
        (here === 'index.html' ? '<li><span aria-current="page">Explore</span></li>'
          : '<li><a href="index.html">Explore</a></li><li><span aria-current="page">' + esc(cur.name) + '</span></li>') +
        '</ol>';
      var nav = '<nav class="mmx-nav" aria-label="Explore the notes"><ul class="ar-nav">' +
        PAGES.map(function (p) {
          return '<li><a href="' + p.href + '"' + (p.href === here ? ' aria-current="page"' : '') + '>' + esc(p.short) + '</a></li>';
        }).join('') + '</ul></nav>';
      head.innerHTML = crumbs +
        '<p class="ar-kicker">' + esc(o.kicker || 'Magick Mica TV · Explore') + '</p>' +
        '<h1 class="ar-title ar-title--chrome">' + esc(o.title || cur.name) + '</h1>' +
        (o.subtitle ? '<p class="ar-subtitle">' + esc(o.subtitle) + '</p>' : '') +
        '<p class="ar-status mmx-status"><span class="ar-light ar-light--tuning" id="mmx-light"></span>' +
        '<span id="mmx-stat">Tuning in…</span></p>' + nav;
    }
    var foot = document.getElementById('mmx-foot');
    if (foot) {
      foot.innerHTML = '<ul class="ar-nav">' +
        [['index.html', 'Home'], ['blog.html', 'Blog'], ['articles.html', 'Articles'],
         ['notes.html', 'Notes'], ['minimags.html', 'Y3K Magazine']].map(function (l) {
          return '<li><a href="' + SITE + l[0] + '">' + l[1] + '</a></li>';
        }).join('') +
        '<li><a href="https://magickmica.substack.com" target="_blank" rel="noopener">Subscribe ↗</a></li></ul>' +
        '<p class="ar-meta mmx-built"></p>';
    }
  }
  /* set the live status line under the title (count etc.) */
  function status(html) {
    var s = document.getElementById('mmx-stat'), l = document.getElementById('mmx-light');
    if (s) s.innerHTML = html;
    if (l) l.className = 'ar-light ar-light--live';
    var b = document.querySelector('.mmx-built');
    if (b && root.MM_NOTES && root.MM_NOTES.built) {
      var last = notes.length ? notes[notes.length - 1].d : '';
      b.textContent = 'Archive through ' + (last ? A.dates.label(last) : '?');
    }
  }
  function fmt(n) { return Number(n).toLocaleString('en-US'); }

  /* ── note card ────────────────────────────────────────────── */
  /* o.onOpen(n): open in the viewer instead of following the link */
  function card(n, o) {
    o = o || {};
    var el = document.createElement('article');
    el.className = 'ar-card mmx-card mmx-card--' + n.kind;
    var media = '';
    if (n.thumb) {
      var ratio = n.w && n.h ? ' style="aspect-ratio:' + n.w + '/' + n.h + '"' : '';
      media = '<div class="ar-media mmx-card__media"' + ratio + '>' +
        '<img src="' + esc(n.thumb) + '" alt="' + esc(n.b ? excerpt(n.b, 100) : (n.kind === 'video' ? 'Video note' : 'Image note')) +
        '" loading="lazy" decoding="async"' + (n.w ? ' width="' + n.w + '" height="' + n.h + '"' : '') + '>' +
        (n.kind === 'video' ? '<span class="ar-badge mmx-card__badge">▶ Video</span>' : '') + '</div>';
    }
    var text = n.b ? '<p class="mmx-card__text">' + esc(excerpt(n.b, o.max || 220)) + '</p>' : '';
    el.innerHTML = media +
      '<div class="mmx-card__body">' + text +
      '<p class="mmx-card__meta"><time datetime="' + n.d + '">' + A.dates.label(n.d) + '</time>' +
      '<span aria-label="' + n.l + ' likes, ' + n.r + ' restacks">♥ ' + n.l + (n.r ? ' · ↻ ' + n.r : '') + '</span></p>' +
      '<a class="ar-card__link mmx-card__link" href="' + n.url + '" target="_blank" rel="noopener">' +
      (o.onOpen ? 'Open transmission' : 'Read on Substack') +
      '<span class="ar-sr-only">: ' + esc(excerpt(n.b, 60) || A.dates.label(n.d)) + '</span></a></div>';
    var img = el.querySelector('img');
    if (img) img.addEventListener('error', function () {
      var w = img.parentNode;
      w.classList.add(n.kind === 'video' ? 'ar-media--video' : 'ar-media--none');
      w.setAttribute('data-fallback', n.kind === 'video' ? 'Video · watch on Substack' : 'Image unavailable');
      w.style.aspectRatio = '';
      img.remove();
    }, { once: true });
    if (o.onOpen) {
      el.querySelector('.mmx-card__link').addEventListener('click', function (e) {
        if (e.metaKey || e.ctrlKey || e.shiftKey || e.button === 1) return;   /* let new-tab clicks through */
        e.preventDefault(); o.onOpen(n);
      });
    }
    return el;
  }

  /* ── viewer: one dialog per page, with prev/next through a list ── */
  var viewer = (function () {
    var dlg, list = [], idx = 0, lastFocus;
    function build() {
      dlg = document.createElement('dialog');
      dlg.className = 'mmx-viewer';
      dlg.setAttribute('aria-label', 'Transmission viewer');
      dlg.innerHTML =
        '<div class="mmx-viewer__inner ar-panel ar-panel--holo">' +
        '<div class="mmx-viewer__bar"><span class="ar-meta" id="mmx-v-pos"></span>' +
        '<button type="button" class="ar-btn ar-btn--ghost" data-act="close" aria-label="Close viewer">✕ Close</button></div>' +
        '<div class="mmx-viewer__stage" id="mmx-v-stage"></div>' +
        '<div class="mmx-viewer__info"><p class="ar-meta" id="mmx-v-meta"></p><div class="mmx-viewer__text" id="mmx-v-text"></div>' +
        '<div class="ar-row"><button type="button" class="ar-btn" data-act="prev" aria-label="Previous transmission">← Prev</button>' +
        '<button type="button" class="ar-btn" data-act="next" aria-label="Next transmission">Next →</button>' +
        '<a class="ar-btn ar-btn--signal" id="mmx-v-link" target="_blank" rel="noopener">Read on Substack ↗</a></div></div></div>';
      document.body.appendChild(dlg);
      dlg.addEventListener('click', function (e) {
        var act = e.target.closest('[data-act]');
        if (act) { var a = act.getAttribute('data-act'); if (a === 'close') close(); else step(a === 'next' ? 1 : -1); return; }
        if (e.target === dlg) close();                      /* backdrop click */
      });
      dlg.addEventListener('keydown', function (e) {
        if (e.key === 'ArrowRight') { step(1); e.preventDefault(); }
        if (e.key === 'ArrowLeft') { step(-1); e.preventDefault(); }
      });
      dlg.addEventListener('close', function () { if (lastFocus && lastFocus.focus) lastFocus.focus(); });
    }
    function show() {
      var n = list[idx];
      var stage = dlg.querySelector('#mmx-v-stage');
      if (n.thumb) {
        stage.innerHTML = '<img alt="' + esc(n.b ? excerpt(n.b, 100) : 'Note image') + '" src="' + esc(n.kind === 'image' ? big(n) : n.thumb) + '">' +
          (n.kind === 'video' ? '<span class="ar-badge mmx-viewer__badge">▶ Video · plays on Substack</span>' : '');
        var im = stage.querySelector('img');
        im.addEventListener('error', function () {
          if (im.src !== n.thumb && n.thumb) { im.src = n.thumb; return; }   /* big size refused: use the original */
          stage.innerHTML = n.kind === 'video'
            ? '<a class="ar-media ar-media--video mmx-viewer__video" href="' + n.url + '" target="_blank" rel="noopener" data-fallback="Video · watch it on Substack"><span class="ar-sr-only">Watch this video on Substack</span></a>'
            : '<div class="ar-media ar-media--none" data-fallback="Image unavailable"></div>';
        });
        stage.hidden = false;
      } else { stage.innerHTML = ''; stage.hidden = true; }
      dlg.querySelector('#mmx-v-meta').textContent = A.dates.label(n.d, 'long') + ' · ♥ ' + n.l + (n.r ? ' · ↻ ' + n.r : '');
      dlg.querySelector('#mmx-v-text').textContent = n.b || '(no text)';
      dlg.querySelector('#mmx-v-link').href = n.url;
      dlg.querySelector('#mmx-v-link').textContent = (n.kind === 'video' ? 'Watch' : 'Read') + ' on Substack \u2197';
      dlg.querySelector('#mmx-v-pos').textContent = list.length > 1 ? (idx + 1) + ' of ' + fmt(list.length) : '';
      dlg.querySelector('[data-act="prev"]').disabled = idx <= 0;
      dlg.querySelector('[data-act="next"]').disabled = idx >= list.length - 1;
    }
    function open(n, within) {
      if (!dlg) build();
      list = within && within.length ? within : [n];
      idx = Math.max(0, list.indexOf(n));
      lastFocus = document.activeElement;
      show();
      if (!dlg.open) { if (dlg.showModal) dlg.showModal(); else dlg.setAttribute('open', ''); }
      dlg.querySelector('[data-act="close"]').focus();
    }
    function step(d) { var j = idx + d; if (j < 0 || j >= list.length) return; idx = j; show(); }
    function close() { if (dlg.close) dlg.close(); else dlg.removeAttribute('open'); }
    return { open: open, close: close };
  })();

  /* render a long list in batches as the reader scrolls */
  function batches(container, items, make, size) {
    size = size || 60;
    var shown = 0, sentinel = document.createElement('div');
    sentinel.className = 'mmx-sentinel';
    var more = document.createElement('button');
    more.type = 'button'; more.className = 'ar-btn mmx-more'; more.textContent = 'Load more';
    function add() {
      var frag = document.createDocumentFragment();
      items.slice(shown, shown + size).forEach(function (it) { frag.appendChild(make(it)); });
      shown = Math.min(items.length, shown + size);
      container.appendChild(frag);
      more.hidden = shown >= items.length;
    }
    more.addEventListener('click', add);
    container.after(more);
    add();
    if ('IntersectionObserver' in root) {
      var io = new IntersectionObserver(function (es) {
        if (es[0].isIntersecting && shown < items.length) add();
      }, { rootMargin: '800px' });
      io.observe(more);
      return { disconnect: function () { io.disconnect(); more.remove(); } };
    }
    return { disconnect: function () { more.remove(); } };
  }

  var api = { notes: notes, byId: byId, ready: ready, chrome: chrome, status: status,
              card: card, viewer: viewer, batches: batches, big: big,
              excerpt: excerpt, firstLine: firstLine, fmt: fmt, esc: esc, PAGES: PAGES };
  root.MMX = api;
})(window);
