#!/usr/bin/env python3
"""
MAGICKMICA · EXPLORE — data builder
-----------------------------------
Reads the site's notes archive (read-only) and writes explore/notes-data.js,
the one data file shared by every page in explore/.

    python3 explore/build_explore.py          # from anywhere

Input  (never modified): _data/notes_with_media_compact.json
                         _data/explore_hidden.json  (optional: note ids to leave out)
Output:                  explore/notes-data.js  ->  window.MM_NOTES = {...};

tools/update_all.py runs this after every site update, the same way it runs
the Almanac, Signal Band and Reader builders, so the Explore pages always show
every note. The pages themselves are hand-written and never regenerated.

Format (kept compact: one row per note, oldest first):
    {"built": "...", "img": "<shared image URL prefix>",
     "notes": [[id, "YYYY-MM-DD", text, image, video, likes, restacks, [tags]], ...]}
  image  = the part after "img" when the URL starts with it, else the full URL, else ""
  video  = Mux playback id, else ""
  tags   = Mica's own hand-added theme tags, else []
Nothing is invented: a missing field stays empty.
"""
import datetime as dt
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.environ.get("MM_DATA") or os.path.join(ROOT, "_data")
OUT = os.path.join(HERE, "notes-data.js")
IMG = ("https://substackcdn.com/image/fetch/$s_!G4Yk!,w_400,c_limit,f_webp,"
       "q_auto:good,fl_progressive:steep/"
       "https%3A%2F%2Fsubstack-post-media.s3.amazonaws.com%2Fpublic%2Fimages%2F")


def main():
    with open(os.path.join(DATA, "notes_with_media_compact.json"), encoding="utf-8") as f:
        notes = json.load(f)
    hidden = set()
    hp = os.path.join(DATA, "explore_hidden.json")
    if os.path.exists(hp):
        with open(hp, encoding="utf-8") as f:
            hidden = {int(h["id"]) for h in json.load(f).get("hidden", [])}
    notes = [n for n in notes if int(n["id"]) not in hidden]
    notes.sort(key=lambda n: (n["d"], int(n["id"])))
    rows = []
    for n in notes:
        t = n.get("t") or ""
        if t.startswith(IMG):
            t = t[len(IMG):]
        rows.append([
            int(n["id"]), n["d"], n.get("b") or "", t, n.get("m") or "",
            int(n.get("l") or 0), int(n.get("r") or 0), list(n.get("c") or []),
        ])
    payload = {
        "built": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%MZ"),
        "img": IMG,
        "notes": rows,
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    # U+2028/2029 are legal in JSON but break older JS parsers
    body = body.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    text = ("/* generated by explore/build_explore.py from _data/ — do not edit by hand */\n"
            "window.MM_NOTES = " + body + ";\n")
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    # keep the file byte-identical when only the timestamp would change,
    # so an update with no new notes does not commit a pointless diff
    def strip(s):
        return s.split('"built":', 1)[-1].split(",", 1)[-1] if s else s
    if old is not None and strip(old) == strip(text):
        print(f"explore/notes-data.js unchanged ({len(rows):,} notes)")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"explore/notes-data.js: {len(rows):,} notes ({len(hidden)} hidden), {len(text) / 1024:,.0f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
