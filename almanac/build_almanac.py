#!/usr/bin/env python3
"""
THE Y3K ALMANAC — data builder
------------------------------
Reads the site's existing data (read-only) and writes almanac/almanac.js.
Touches nothing outside the almanac/ folder.

    python3 almanac/build_almanac.py          # from the repo root

Inputs  (never modified): _data/notes_with_media_compact.json,
                          _data/magazine_articles.json, minimags.html
Output:                   almanac/almanac.js  ->  const ALMANAC = {...};
"""
import datetime as dt
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# Data folder: the repo's _data/ by default; set MM_DATA to build from another copy.
DATA = os.environ.get("MM_DATA") or os.path.join(ROOT, "_data")
OUT = os.path.join(HERE, "almanac.js")
PER_DAY = 16            # notes kept per calendar day (most-loved first)
IMG_PREFIX = ("https://substackcdn.com/image/fetch/$s_!G4Yk!,w_400,c_limit,f_webp,"
              "q_auto:good,fl_progressive:steep/"
              "https%3A%2F%2Fsubstack-post-media.s3.amazonaws.com%2Fpublic%2Fimages%2F")
URL_RE = re.compile(r"https?://\S+")


def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def clean(t, limit=320):
    t = re.sub(r"\s+", " ", URL_RE.sub("", t or "")).strip()
    if len(t) > limit:
        t = t[:limit].rsplit(" ", 1)[0].rstrip(",.;:") + "…"
    return t


def main():
    notes = load(os.path.join(DATA, "notes_with_media_compact.json"))
    articles = load(os.path.join(DATA, "magazine_articles.json"))
    with open(os.path.join(ROOT, "minimags.html"), encoding="utf-8") as f:
        issued = sorted(set(re.findall(r'href="((?:week|month)-[\d-]+)\.html"', f.read())))

    days, counts = {}, {}
    for n in notes:
        md, y = n["d"][5:], n["d"][:4]
        counts.setdefault(md, {}).setdefault(y, 0)
        counts[md][y] += 1
        days.setdefault(md, []).append(n)

    out_days = {}
    for md, group in days.items():
        group.sort(key=lambda n: (n.get("l", 0), n.get("r", 0)), reverse=True)
        keep = []
        for n in group:
            x = clean(n.get("b", ""))
            if not x and "t" not in n:
                continue
            row = [n["d"], n["id"], x, n.get("l", 0)]
            t = n.get("t")
            if t:
                row.append(t[len(IMG_PREFIX):] if t.startswith(IMG_PREFIX) else t)
            keep.append(row)
            if len(keep) == PER_DAY:
                break
        out_days[md] = keep

    arts = {}
    for a in articles:
        arts.setdefault(a["date"][5:], []).append({
            "d": a["date"], "t": a["title"].strip(), "s": (a.get("subtitle") or "").strip(),
            "u": a["url"], "nl": "Art" if "Art" in a.get("newsletter", "") else "TV",
            "p": clean(a.get("preview", ""), 260),
        })

    data = {
        "built": dt.date.today().isoformat(),
        "total": len(notes),
        "first": min(n["d"] for n in notes),
        "last": max(n["d"] for n in notes),
        "imgPrefix": IMG_PREFIX,
        "counts": counts,
        "days": out_days,
        "articles": arts,
        "issued": [i for i in issued],
    }
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* generated by almanac/build_almanac.py — do not edit by hand */\n")
        f.write(f"const ALMANAC = {payload};\n")
    print(f"almanac.js: {len(out_days)} calendar days with notes, {len(notes):,} notes, "
          f"{len(articles)} articles, {os.path.getsize(OUT)/1024:.0f} KB")


if __name__ == "__main__":
    main()
