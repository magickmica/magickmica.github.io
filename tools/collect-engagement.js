/* ============================================================
   MAGICK MICA · COLLECT ENGAGEMENT
   ------------------------------------------------------------
   Who comments, what they said, and what you have not replied to.
   Feeds people.html.

   HOW TO RUN
   1. Go to https://magickmica.substack.com  (any page, signed in)
   2. F12 -> Console. If Chrome asks, type:  allow pasting   then Enter
   3. Paste this whole file, press Enter, and leave it alone.
      It walks every post, so give it a minute or two.
   4. engagement.js downloads at the end. Put it in the repo root,
      next to people.html.

   CHANGES FROM THE FIRST RUN
   - Captures each post's slug, so people.html can deep-link to the
     exact comment instead of only the commenter's profile.
   - Writes engagement.js (a plain `const`) rather than .json, matching
     pools.js and products.js — a <script src> with no fetch, so the
     page also works when previewed straight off disk.
   - Replies are flattened recursively. Substack's comment_count counts
     replies too, so a collector that only reads the top level quietly
     loses half the conversation.
   ============================================================ */
(async () => {
  'use strict';

  const ME = 'magickmica';          // your handle — decides "did I reply?"
  const PAUSE = 350;                // be polite to the API

  const log = (...a) => console.log('%c[orbit]', 'color:#F5C044', ...a);
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const j = async (u) => {
    try { const r = await fetch(u, { credentials: 'include' });
          return r.ok ? await r.json() : null; }
    catch (e) { return null; }
  };

  /* ---- 1. every post ---- */
  const posts = [];
  for (let off = 0; off < 2000; off += 50) {
    const batch = await j('/api/v1/posts?limit=50&offset=' + off);
    if (!Array.isArray(batch) || !batch.length) break;
    posts.push(...batch);
    log('posts…', posts.length);
    await sleep(PAUSE);
  }
  log('posts found:', posts.length);
  if (!posts.length) { log('%cNo posts came back — are you on magickmica.substack.com?', 'color:#FF4FA3'); return; }

  /* ---- 2. every comment, replies included ---- */
  const flat = [];
  const walk = (c, postId, depth, parent) => {
    flat.push({
      id: c.id, post_id: postId, depth, parent,
      user_id: c.user_id, name: c.name, handle: c.handle || null,
      photo: c.photo_url || null, date: c.date,
      body: (c.body || '').trim(),
      likes: c.reaction_count || 0,
      likedBy: c.reactor_names || [],
      restacks: c.restacks || 0,
      tier: c.user_bestseller_tier || null,
    });
    (c.children || []).forEach((k) => walk(k, postId, depth + 1, c.id));
  };

  const withComments = posts.filter((p) => (p.comment_count || 0) > 0);
  log('posts with comments:', withComments.length);
  let n = 0;
  for (const p of withComments) {
    const c = await j('/api/v1/post/' + p.id + '/comments?all_comments=true');
    const arr = Array.isArray(c) ? c : (c && c.comments) || [];
    arr.forEach((x) => walk(x, p.id, 0, null));
    if (++n % 10 === 0) log('  ' + n + '/' + withComments.length + ' posts · ' + flat.length + ' comments');
    await sleep(PAUSE);
  }

  /* ---- 3. roll up into people ---- */
  const mine = new Set(flat.filter((c) => c.handle === ME).map((c) => c.id));
  const repliedTo = new Set(flat.filter((c) => mine.has(c.id) && c.parent).map((c) => c.parent));
  const people = {};
  flat.forEach((c) => {
    if (c.handle === ME) return;
    const k = c.user_id || c.name;
    const p = people[k] || (people[k] = {
      user_id: c.user_id, name: c.name, handle: c.handle, photo: c.photo,
      comments: 0, likesReceived: 0, posts: new Set(),
      first: c.date, last: c.date, unanswered: 0, tier: c.tier,
    });
    p.comments++;
    p.likesReceived += c.likes;
    p.posts.add(c.post_id);
    if (c.date < p.first) p.first = c.date;
    if (c.date > p.last) p.last = c.date;
    if (!repliedTo.has(c.id)) p.unanswered++;
  });
  const list = Object.values(people)
    .map((p) => ({ ...p, posts: p.posts.size }))
    .sort((a, b) => b.comments - a.comments);

  const postTitles = {}, postSlugs = {};
  posts.forEach((p) => { postTitles[p.id] = p.title; if (p.slug) postSlugs[p.id] = p.slug; });

  const collected = new Date().toISOString().slice(0, 10);
  const out = { collected, me: ME, posts: posts.length,
                postTitles, postSlugs, comments: flat, people: list };

  const body =
    '/* MAGICK MICA — engagement snapshot. Generated by tools/collect_engagement.js.\n' +
    '   Collected ' + collected + '. Do not edit by hand. */\n' +
    'const ENGAGEMENT = ' + JSON.stringify(out) + ';\n';

  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([body], { type: 'application/javascript' }));
  a.download = 'engagement.js';
  document.body.appendChild(a);
  a.click();
  setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 4000);

  /* ---- diagnostics: check these before uploading ---- */
  const expect = withComments.reduce((s, p) => s + (p.comment_count || 0), 0);
  const slugged = Object.keys(postSlugs).length;
  log('── REPORT ──────────────────────');
  log('posts                 :', posts.length);
  log('  with a slug         :', slugged, '(want ' + posts.length + ' — deep links need it)');
  log('comments collected    :', flat.length, '(site says ' + expect + ')');
  log('  of those, yours     :', mine.size, '(want > 0 — else ME is wrong)');
  log('distinct people       :', list.length);
  log('unanswered            :', list.reduce((s, p) => s + p.unanswered, 0));
  log('top 5:', list.slice(0, 5).map((p) => p.name + ' (' + p.comments + ')'));
  window.__orbit = out;
})();
